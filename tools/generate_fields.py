#!/usr/bin/env python3
"""Build field descriptors from the reviewed schema; no device/image operations."""
import json,re
from pathlib import Path
here=Path(__file__).resolve().parent.parent
s=json.loads((here/'schema/stats.schema.json').read_text())
p=s['properties']['ports']['prefixItems'][0]['properties'];poe=p['poe']['anyOf'][0]['properties']
groups={'system':s['properties']['system']['properties'],'global_poe':s['properties']['poe']['properties'],'port':{k:v for k,v in p.items() if k not in ['port','counters','poe']},'counter':p['counters']['properties'],'poe':{k:v for k,v in poe.items() if k!='recovery'},'recovery':poe['recovery']['properties'],'loop':s['properties']['loop_prevention']['properties']}
ids=[];lines=['/* Generated by generate_fields.py from stats.schema.json. */']
for group,props in groups.items():
 lines.append('static const struct field '+group+'_fields[] = {')
 for name,v in props.items():
  id='SG_'+(group+'_'+('description' if group=='system' and name=='name' else name)).upper()
  if id not in ids:ids.append(id)
  forced=v.get('type')=='null' or name=='rx_discards'
  typ=v.get('type',[]);enum=v.get('enum',[]);flags='F_NULL' if forced else ('F_COUNTER' if group=='counter' else 'F_BOOL' if 'boolean' in typ else 'F_TEXT' if 'string' in typ or any(isinstance(x,str) for x in enum) else 'F_NUMBER' if 'number' in typ else 'F_UINT')
  choices={('port','speed_mbps'):'R_SPEED',('port','duplex'):'R_DUPLEX',('poe','power_limit_mode'):'R_LIMIT',('poe','pd_class'):'R_CLASS',('system','uptime_ticks_raw'):'R_U32'}
  rule='R_U32' if group=='loop' and name!='enabled' else choices.get((group,name),'R_NONE')
  lines.append(' {"'+name+'", '+id+', '+flags+', '+rule+', '+str(v.get('maxLength',128))+'},')
 lines.append('};')
(here/'include/sg_fields.h').write_text('#ifndef SG_FIELDS_H\n#define SG_FIELDS_H\nenum sg_field {\n '+',\n '.join(ids)+',\n SG_FIELD_COUNT\n};\n#endif\n')
(here/'src/sg_fields.inc').write_text('\n'.join(lines)+'\n')
print('Generated',len(ids),'source fields')
